#!/usr/bin/env python3
"""Write port/vita/boot_trace.S from port/vita/boot_trace_steps.txt."""
import sys
steps_path, out_path = sys.argv[1], sys.argv[2]
names = [l.strip() for l in open(steps_path) if l.strip() and not l.startswith('#')]
o = ["@ Boot trace for gate 11 (GCC / PS Vita): entry logging for the steps of the",
     "@ game start-up (NitroStartUp, NitroMain -> func_0201a054) and the main loop.",
     "@ Each step is linked with --wrap=<name>; its __wrap_ entry logs the name and",
     "@ tail-calls __real_<name> with every argument register untouched, so the last",
     "@ line in the log is the step the game is in if it stops.",
     "@ Generated by port/tools/gen_boot_trace.py -- edit boot_trace_steps.txt.",
     "    .syntax unified", "    .thumb", "    .text"]
for i, n in enumerate(names):
    o += [f'    .section .rodata.sm64ds_trace_{i},"a"', f"sm64ds_trace_name_{i}:",
          f'    .asciz "{n}"', f'    .section .text.__wrap_{n},"ax",%progbits',
          f"    .global __wrap_{n}", "    .thumb_func", f"    .type __wrap_{n}, %function",
          f"__wrap_{n}:", "    push {r0, r1, r2, r3, r4, lr}",
          f"    ldr r0, =sm64ds_trace_name_{i}", "    bl sm64ds_boot_trace",
          "    pop {r0, r1, r2, r3, r4, lr}", f"    b.w __real_{n}", "    .ltorg"]
open(out_path, 'w').write("\n".join(o) + "\n")
