#!/usr/bin/env python3
"""Rewrite sm64ds-decomp sources for the host build.

The decomp's `src/` is byte-verified against the ROM and must not change. This
reads it and emits a transformed copy into build/host-src/, so the port never
edits the matched tree. See notes/assessment.md section 0c.

Currently rewrites direct MMIO cast-derefs:

    *(volatile unsigned short *)0x4000280      ->  NTR_MMIO(unsigned short, 0x4000280)

which routes the access through include/ntr/mmio.h so that write-triggered
registers run their side effect. Accesses the transform cannot see textually --
a pointer bound to a register and dereferenced later -- still work, because the
host maps real memory at the DS I/O addresses; they just do not trigger.

    python tools/hostgen.py --decomp ../sm64ds-decomp _ZN4cstd3divEii
    python tools/hostgen.py --decomp ../sm64ds-decomp --all
"""

import argparse
import pathlib
import re
import sys

# *(volatile TYPE *)0xADDR   ->  NTR_MMIO(TYPE, 0xADDR)
# TYPE is a plain builtin spelling; the decomp never casts to anything else
# here. `volatile` is optional: matched code also reaches registers through
# plain casts (the material bind stores POLYGON_ATTR/TEXIMAGE without it),
# and any literal-address deref in the 0x04xxxxxx window is MMIO by
# definition.
# Two textual shapes: `*(T *)0xADDR` and `*((T *)0xADDR)`. The conditional
# group consumes the trailing paren only when the extra leading one matched,
# so computed addresses like `*(volatile u32 *)(0xADDR + x)` are left alone
# (they resolve through the mapped latch window, which is correct for reads).
MMIO_DEREF = re.compile(
    r"\*\s*(\()?\s*\(\s*(?:volatile\s+)?"
    r"((?:unsigned|signed|long|short|int|char|v?[us](?:8|16|32|64))"
    r"(?:\s+(?:unsigned|signed|long|short|int|char))*)"
    r"\s*\*\s*\)\s*(0x0?4[0-9A-Fa-f]{6})[uU]?\b(?(1)\s*\))"
)

HEADER = """// GENERATED by tools/hostgen.py from {src}
// Do not edit. The source of truth is the byte-verified decomp; edit the
// transform or the host I/O layer instead.
#include "ntr/mmio.h"

"""


# mwccarm allows void*+int (byte arithmetic, the pret void*-arith idiom);
# MSVC C++ rejects it. Retype the pointee to char* only where the deref
# feeds an addition -- the value is identical, the arithmetic becomes legal.
VOIDPP_ARITH = re.compile(r"\(\s*\*\s*\(\s*\(\s*void\s*\*\*\s*\)\s*([^()]+?)\s*\)\s*\)\s*\+")

# GCC-style attributes (long_call, target("thumb")) mean nothing to MSVC.
# One nesting level inside the (( )) is enough for every use in src/.
ATTRIBUTE = re.compile(r"__attribute__\s*\(\((?:[^()]|\([^()]*\))*\)\)")


# Any OTHER cast of a literal DS address to a pointer -- `(u16 *)0x06800000`,
# `(vu32 *)0x040000b0` held in a pointer for computed access, main-RAM shared
# words -- becomes a host_ptr() lookup. Identity on hosts that map the regions
# at their real addresses (Windows/Linux PC); a translation where the OS cannot
# (the PS Vita, NTR_RELOCATE_REGIONS). Runs after MMIO_DEREF, so literal
# register derefs keep their side-effect proxy.
DS_PTR_CAST = re.compile(
    r"\(\s*((?:const\s+)?(?:volatile\s+)?"
    # any type name: `(name *)` right before a literal can only be a cast
    r"(?:(?:struct|union|enum)\s+\w+|unsigned|signed|long|short|int|char|void|[A-Za-z_]\w*)"
    r"(?:\s+(?:unsigned|signed|long|short|int|char))*"
    r"\s*\*+)\s*\)\s*(0x0?[2-7][0-9A-Fa-f]{6})[uU]?\b"
)


# The same cast spelled through an address macro -- `(OSLockWord *)HW_INIT_LOCK_BUF`
# -- that the text never shows as a literal. Every `#define NAME 0x02xxxxxx`
# (a bare DS address, 0x02..0x07) in include/ and in the TU itself counts.
DS_ADDR_DEFINE = re.compile(
    r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)[ \t]+\(?[ \t]*(0x0?[2-7][0-9A-Fa-f]{6})[uU]?[ \t]*\)?[ \t]*(?:/[*/].*)?$",
    re.MULTILINE)
_CAST_TYPE = DS_PTR_CAST.pattern[: DS_PTR_CAST.pattern.index(r"\s*\)\s*(0x0?")]
_header_macros = None


def _ds_macros(text):
    global _header_macros
    if _header_macros is None:
        _header_macros = set()
        inc = pathlib.Path(__file__).resolve().parents[2] / "include"
        for h in inc.rglob("*.h"):
            for m in DS_ADDR_DEFINE.finditer(h.read_text(encoding="utf-8", errors="replace")):
                _header_macros.add(m.group(1))
    return _header_macros | {m.group(1) for m in DS_ADDR_DEFINE.finditer(text)}


def _macro_cast_re(text):
    names = _ds_macros(text)
    if not names:
        return None
    alt = "|".join(sorted(map(re.escape, names), key=len, reverse=True))
    return re.compile(_CAST_TYPE + r"\s*\)\s*(" + alt + r")\b")


_SUM_CAST_HEAD = None


_DS_LIT = re.compile(r"\(?\s*0x0?[2-7][0-9A-Fa-f]{6}[uU]?\s*\)?$")


def _top_terms(expr):
    """The top-level `+` terms of expr (nothing nested in parentheses split)."""
    terms, depth, cur = [], 0, []
    for ch in expr:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "+" and depth == 0:
            terms.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    terms.append("".join(cur))
    return [t.strip() for t in terms]


def _sum_casts(text):
    """`(T *)(0x027ffe00 + 0x40)`, `(T *)(HW_ROM_HEADER_BUF + off)`,
    `(void *)((r1 << 0xb) + 0x6200000)`: a DS address computed as a sum with a
    literal or an address macro as one of its top-level terms, cast to a
    pointer. The whole parenthesised sum goes through host_ptr. A literal
    under `&`, `|` or a shift is a mask, not a base, and is left alone.
    Returns (text, count)."""
    names = _ds_macros(text)
    head = re.compile(_CAST_TYPE + r"\s*\)\s*\(")
    out, pos, n = [], 0, 0
    while True:
        m = head.search(text, pos)
        if not m:
            break
        cast_type = m.group(1)
        open_at = m.end() - 1
        depth, i = 0, open_at
        while i < len(text):
            if text[i] == "(":
                depth += 1
            elif text[i] == ")":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        expr = text[open_at + 1:i]
        terms = _top_terms(expr)
        is_addr = len(terms) > 1 and "::ntr::host_ptr" not in expr and any(
            _DS_LIT.match(t) or t.strip("() ") in names for t in terms)
        if not is_addr:
            out.append(text[pos:m.end()])
            pos = m.end()
            continue
        out.append(text[pos:m.start()])
        out.append(f"(({cast_type})::ntr::host_ptr({expr}))")
        pos = i + 1
        n += 1
    out.append(text[pos:])
    return "".join(out), n


def _proxy_type(t):
    """The SDK's vu32/vs16... are `volatile` typedefs. The proxy already routes
    every access through the I/O layer, so it takes the plain type: vu32 -> u32.
    These were missed before, and on a fixed-map host silently became raw
    memory accesses -- reads worked, write-triggered side effects did not."""
    t = t.strip()
    return t[1:] if re.fullmatch(r"v[us](?:8|16|32|64)", t) else t


# A pointer variable aimed at a 3D geometry port (0x04000400..0x040005FF) and
# written through: `port = (volatile int *)0x4000458; *port = xx; ...` (G3i's
# perspective load, ModelComponents' scale, overlay 7's texcoords). A store
# through a plain pointer is a memory write the 3D engine never sees, so each
# `*port = v;` becomes a register write, as the DS hardware takes it.
GX_PORT_PTR = re.compile(
    r"\b(\w+)\s*=\s*\(\s*(?:volatile\s+)?(?:int|u32|s32|unsigned(?:\s+int)?|vu32)\s*\*\s*\)"
    r"\s*(0x0?40004[0-9A-Fa-f]{2}|0x0?40005[0-9A-Fa-f]{2})\s*;")


def _gx_port_stores(text):
    """Within the function that aims `name` at a port: each statement
    `*name = v;` (not a declaration) becomes a register write."""
    n = 0
    while True:
        done = True
        for m in GX_PORT_PTR.finditer(text):
            name, addr = m.group(1), m.group(2)
            # the rest of the function: up to its closing brace, which sits
            # at the start of a line in this tree
            fe = re.compile(r"\n\}").search(text, m.end())
            end = fe.start() if fe else len(text)
            body = text[m.end():end]
            store = re.compile(r"(^|[;{}]|\n)(\s*)\*\s*" + re.escape(name) + r"\s*=(?!=)\s*([^;]+);")
            new_body, k = store.subn(
                lambda s: f"{s.group(1)}{s.group(2)}::ntr::io_write({addr}u, (uint32_t)({s.group(3)}), 4);",
                body)
            if k:
                # keep the assignment for anything else that reads the pointer
                text = text[:m.end()] + new_body + text[end:]
                n += k
                done = False
                break
        if done:
            return text, n


# A TU's own register-access macro, `#define REG16(a) (*(volatile u16 *)(a))`
# (the stage scene's pause screen writes BGCNT through it): the deref is in
# the macro body with a parameter for the address, which MMIO_DEREF cannot
# see. Rewritten to the MMIO proxy, every use goes through io_read/io_write.
REG_MACRO = re.compile(
    r"#define\s+(\w+)\(\s*(\w+)\s*\)\s+\(\s*\*\s*\(\s*(volatile\s+u(?:8|16|32)|vu(?:8|16|32))\s*\*\s*\)\s*\(\s*\2\s*\)\s*\)")


def _reg_macros(text):
    def rep(m):
        t = m.group(3).split()[-1]          # "volatile u16" / "vu16" -> u16
        t = t[1:] if t.startswith("v") else t
        return f"#define {m.group(1)}({m.group(2)}) NTR_MMIO({_proxy_type(t)}, ({m.group(2)}))"
    return REG_MACRO.subn(rep, text)


def transform(text):
    """Return (new_text, n_rewrites)."""
    text, n7 = _reg_macros(text)
    text, n0 = _gx_port_stores(text)
    text, n3 = ATTRIBUTE.subn("", text)
    text, n2 = VOIDPP_ARITH.subn(r"((*((char **) \1))) +", text)
    text, n1 = MMIO_DEREF.subn(lambda m: f"NTR_MMIO({_proxy_type(m.group(2))}, {m.group(3)})", text)
    text, n4 = DS_PTR_CAST.subn(
        lambda m: f"(({m.group(1)})::ntr::host_ptr({m.group(2)}))", text)
    n5 = 0
    mc = _macro_cast_re(text)
    if mc:
        text, n5 = mc.subn(lambda m: f"(({m.group(1)})::ntr::host_ptr({m.group(2)}))", text)
    text, n6 = _sum_casts(text)
    return text, n0 + n1 + n2 + n3 + n4 + n5 + n6 + n7


# ~110 files in the decomp are ARM assembly blocks -- CP15 cache ops, the CRT0,
# SWI wrappers, context switches. They are matched and correct, and they are also
# the one thing a host compiler can never consume. They are not transformed; they
# are reimplemented by hand in src/port/runtime.cpp. This is the port's shim
# surface, and keeping it enumerable is the point.
ASM_BLOCK = re.compile(r"^\s*(?:extern\s+\"C\"\s+)?(?:__)?asm\s", re.MULTILINE)


def is_asm(text):
    return bool(ASM_BLOCK.search(text))


def emit(src_path, out_dir, decomp_root, strip_asm=False):
    text = src_path.read_text(encoding="utf-8", errors="replace")
    if strip_asm:
        # GCC builds: drop the TU's hand-written asm functions first (see
        # port/tools/hostexterns.py strip_asm; the host provides each one
        # natively) so the rest of the TU still gets its MMIO rewrites
        sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
        import hostexterns
        text = "".join(hostexterns.strip_asm(text.splitlines(keepends=True)))
    # The decomp marks C++ files with a leading `//cpp` line; the host build
    # compiles everything as C++ anyway, so drop it.
    text = re.sub(r"\A//cpp[^\n]*\n", "", text)
    new, n = transform(text)
    # Everything is emitted as C++ (NTR_MMIO expands to a template proxy), but
    # a .c source's symbols must keep C linkage: the port's other slices
    # compile the decomp's .c files as real C, and mixing linkages per-symbol
    # is exactly the bug class the HAL bridges exist to catch. The decomp's
    # own headers are C-only typedefs, so including them inside the wrap is
    # sound.
    if src_path.suffix == ".c":
        new = 'extern "C" {\n' + new + '\n}  /* extern "C" (hostgen: .c source) */\n'
    rel = src_path.relative_to(decomp_root)
    out = out_dir / rel.with_suffix(".cpp")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(HEADER.format(src=rel.as_posix()) + new, encoding="utf-8")
    return out, n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("symbols", nargs="*", help="symbol names to transform (no extension)")
    # This tool lives at port/tools/hostgen.py inside the decomp itself.
    ap.add_argument("--decomp",
                    default=str(pathlib.Path(__file__).resolve().parents[2]))
    ap.add_argument("--out", default="build/host-src")
    ap.add_argument("--all", action="store_true", help="transform every file in src/")
    # Console builds (port/vita) pick their hostgen set automatically: any slice
    # file that touches a DS address must go through the transform there,
    # because nothing is mapped at those addresses.
    ap.add_argument("--strip-asm", action="store_true",
                    help="drop asm functions instead of skipping the TU (GCC builds)")
    ap.add_argument("--paths", nargs="+", metavar="FILE",
                    help="transform these files (paths relative to --decomp)")
    ap.add_argument("--needs", nargs="+", metavar="FILE",
                    help="print, one per line, those of FILE that touch a DS "
                         "address (register deref or pointer cast) in code")
    args = ap.parse_args()

    decomp = pathlib.Path(args.decomp).expanduser().resolve()
    src = decomp / "src"
    if not src.is_dir():
        sys.exit(f"no src/ under {decomp} -- pass --decomp")
    out_dir = pathlib.Path(args.out)

    if args.needs:
        for rel in args.needs:
            text = (decomp / rel).read_text(encoding="utf-8", errors="replace")
            code = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
            code = re.sub(r"//[^\n]*", "", code)
            mc = _macro_cast_re(text)
            if (MMIO_DEREF.search(code) or DS_PTR_CAST.search(code) or (mc and mc.search(code))
                    or GX_PORT_PTR.search(code)
                    or _sum_casts(code)[1]):
                print(rel)
        return
    if args.paths:
        targets = [(decomp / rel).resolve() for rel in args.paths]
    elif args.all:
        targets = [p for p in src.rglob("*") if p.suffix in (".c", ".cpp")]
    else:
        # The production enrollment table is authoritative once a reconstructed
        # translation unit owns more than one symbol.  Import from the selected
        # checkout rather than assuming this script's checkout when --decomp is used.
        sys.path.insert(0, str(decomp / "tools"))
        import srcpath  # noqa: PLC0415

        srcpath.set_root(decomp)
        targets = []
        for name in args.symbols:
            hit = srcpath.path_for(name)
            if hit is None:
                sys.exit(f"not found in decomp src/: {name}")
            if hit not in targets:
                targets.append(hit)
        if not targets:
            sys.exit("nothing to do -- pass symbol names or --all")

    total = 0
    skipped = []
    for path in targets:
        text = path.read_text(encoding="utf-8", errors="replace")
        if is_asm(text) and args.strip_asm:
            out, n = emit(path, out_dir, decomp, strip_asm=True)
            total += n
            if not args.all:
                print(f"{path.name:<44} {n:>3} MMIO rewrite(s), asm dropped -> {out}")
            continue
        if is_asm(text):
            skipped.append(path.stem)
            if not args.all:
                print(f"{path.name:<44}   ARM asm -- needs a host implementation")
            continue
        out, n = emit(path, out_dir, decomp)
        total += n
        if not args.all:
            print(f"{path.name:<44} {n:>3} MMIO rewrite(s) -> {out}")

    if args.all:
        print(f"{len(targets) - len(skipped):,} files transformed, "
              f"{total:,} MMIO rewrites -> {out_dir}")
        print(f"{len(skipped):,} ARM asm files skipped (the port's shim surface)")
        manifest = out_dir / "asm-shims.txt"
        manifest.parent.mkdir(parents=True, exist_ok=True)
        manifest.write_text("\n".join(sorted(skipped)) + "\n", encoding="utf-8")
        print(f"  -> {manifest}")


if __name__ == "__main__":
    main()
